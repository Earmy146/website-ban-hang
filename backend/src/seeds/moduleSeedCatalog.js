export function getDefaultModuleConfig(slug, title = 'Cấu hình phân hệ') {
  const cleanSlug = String(slug || 'general').trim().toLowerCase();
  const matched = moduleConfigsSeed.find((cfg) => cfg.slug === cleanSlug);
  if (matched) {
    return structuredClone(matched);
  }
  return {
    slug: cleanSlug,
    title,
    group: 'Cài đặt chuyên sâu',
    updatedBy: 'Alex Chen',
    settings: {
      enabled: true,
      autoSync: true,
      note: `Cấu hình tiêu chuẩn cho phân hệ ${title}`,
    },
  };
}

